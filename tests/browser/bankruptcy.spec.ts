import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { applyAction, createInitialState } from '../../src/core/game';
import { decodeSave, encodeSave } from '../../src/core/save';
import { translations } from '../../src/i18n';

for (const locale of ['pl', 'en'] as const) test(`bankruptcy settles, survives import and restarts from its illustrated ending (${locale})`, async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  const state = { ...applyAction(createInitialState(17), 'skip-intro').state, clockMinutes: 840, money: -1000 };
  await page.locator('#control-saves').click();
  await page.locator('#save-input').setInputFiles({ name: 'closing.npsave', mimeType: 'application/gzip', buffer: Buffer.from(encodeSave(state)) });
  await expect(page.getByRole('status')).toContainText('Zapis wczytany');
  await page.locator('#control-back').click();
  await page.locator('#control-start').click();
  await page.locator(`#control-language-${locale}`).click();
  await page.locator('#control-end-day-home').click();
  await expect(page.locator('#controls')).toHaveAttribute('data-home-kind', 'budget');
  await page.locator('#control-home-next').focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#controls')).toHaveAttribute('data-home-kind', 'bankruptcy');
  const q = translations[locale].progression;
  await expect(page.locator('#control-home-next')).toHaveAccessibleName(q.restartGame);
  await expect(page.locator('#screen-description')).toContainText(q.bankruptcyDescription);
  await expect(page.locator('#screen-description')).toContainText(q.gameOver);
  await expect(page.locator('#stage')).toHaveAttribute('data-art-ready', 'true');
  await page.locator('#stage').screenshot({ path: info.outputPath(`bankruptcy-${locale}.png`) });
  await page.locator('#control-saves').click();
  const pending = page.waitForEvent('download');
  await page.locator('#control-export').click();
  const download = await pending, path = info.outputPath('bankruptcy.npsave');
  await download.saveAs(path);
  const buffer = await readFile(path), ended = decodeSave(buffer);
  expect(ended).toMatchObject({ ending: 'bankruptcy', phase: 'home', day: 1 });
  expect(applyAction(ended, 'next-day').state).toEqual(ended);
  await page.locator('#save-input').setInputFiles({ name: 'bankruptcy.npsave', mimeType: 'application/gzip', buffer });
  await expect(page.getByRole('status')).toContainText(/Zapis wczytany|Save loaded/);
  await page.locator('#save-input').setInputFiles({ name: 'broken.npsave', mimeType: 'application/gzip', buffer: Buffer.from('broken') });
  await expect(page.getByRole('status')).toContainText(/Nieprawidłowy|Invalid/);
  await page.locator('#control-back').click();
  await expect(page.locator('#controls')).toHaveAttribute('data-home-kind', 'budget');
  await page.locator('#control-home-next').click();
  await expect(page.locator('#controls')).toHaveAttribute('data-home-kind', 'bankruptcy');
  if (locale === 'pl') await page.locator('#control-home-next').click();
  else {
    await page.locator('#control-home-next').focus();
    await page.keyboard.press('Enter');
  }
  await expect(page.locator('#controls')).toHaveAttribute('data-screen', 'intro');
  for (let i = 0; i < 4; i++) await page.locator('#control-intro-next').click();
  await expect(page.locator('#control-call-patient')).toBeEnabled();
  await page.locator('#control-saves').click();
  const freshPending = page.waitForEvent('download');
  await page.locator('#control-export').click();
  const fresh = await freshPending, freshPath = info.outputPath('new-game.npsave');
  await fresh.saveAs(freshPath);
  expect(decodeSave(await readFile(freshPath))).toMatchObject({ ending: null, day: 1, money: 0, papers: [], patientsProcessed: 0, visit: null });
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain('bankruptcy');
  expect(errors).toEqual([]);
});
